"""
공간 색.

**색약이어도 서로 구분되는 것**이 첫 번째 기준이다. 색상만 벌려 놓는 것으로는
안 된다 — 적록색약에서는 빨강·주황·갈색·초록이 한데 뭉치기 때문에, 색상환에서
아무리 떨어뜨려도 같은 색이 된다. 실제로 이전 팔레트는 정상 시야에서 최소 ΔE00 이
14.9 였지만 제2색맹에서는 빨강(#B91C1C)과 올리브(#4D7C0F)가 **2.0** 으로 붙었다.
사실상 같은 색이다.

그래서 색상 대신 **명도와 청-황 축**을 쓴다. 이 둘은 적록색약에서도 남는다.
지금 팔레트는 정상 시야와 세 가지 색각이상 전부에서 최소 ΔE00 이 13 이상이다.
팔레트가 밝은 색까지 쓰는 것도 명도 축을 살리기 위해서다 — 밝은 색 위에는 흰 글씨가
안 읽히므로 웹이 `lib/color.ts: onColor` 로 글씨 색을 골라 얹는다.

`zones/tests.py` 가 이 조건들을 지킨다. 색을 바꾸면 테스트가 먼저 막는다.
"""

# 순서도 의미가 있다. 공간 두세 개만 쓰는 사람이 대부분이라, 앞쪽일수록 서로
# 멀도록 배열했다. 앞 2색은 ΔE00 48.6, 3색은 26.7, 전부 쓰면 13.2 로 완만히 준다.
PALETTE = [
    "#007E3F",  # 초록
    "#313BB5",  # 남색
    "#7786FF",  # 하늘보라
    "#BC487D",  # 분홍
    "#5AA202",  # 연두
    "#90164D",  # 자주
    "#EB6575",  # 산호
    "#5C65BD",  # 청보라
]

# 예전 자동 배정 값들. 사용자가 고른 적 없는 색이라 마이그레이션에서 옮겨도 안전하다.
LEGACY_PALETTE = [
    # 최초 팔레트
    "#2F7A63", "#B4741F", "#3E6EA8", "#8A5AA8",
    "#B4544B", "#4E8C43", "#2F7A7A", "#7A6A4F",
    # 색상만 벌려 놓았던 두 번째 팔레트 (색약 대응 이전)
    "#0E7490", "#1D4ED8", "#7E22CE", "#BE185D",
    "#B91C1C", "#B45309", "#4D7C0F",
]


def next_color(used: list[str]) -> str:
    """안 쓴 색을 먼저 준다. 팔레트를 다 쓰면 처음부터 다시 돈다."""
    for color in PALETTE:
        if color not in used:
            return color
    return PALETTE[len(used) % len(PALETTE)]
